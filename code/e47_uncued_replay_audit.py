#!/usr/bin/env python3
"""Audit neutral insertions against a full replay of their uncued baselines.

The replay is generated by e47_neutral_insertion.py; this script never loads a
model. An archived neutral run without a runtime record cannot be certified as
having shared the replay environment, even if its answers happen to match.
"""
from __future__ import annotations

import argparse
import csv
import json
import random
from collections import defaultdict
from pathlib import Path

from e47_design import atomic
from e47_echo_rescore import answer_v2
from e47_neutral_insertion import (
    LETTERS, PAPER_MODELS, PAPER_TASKS, config_changes, config_for,
    fingerprint_sha, frozen_episode_answer, load_progress, load_replay,
    load_source, neutral_answer_fn,
)

SCHEMA = 'e47_uncued_replay_audit_v1'


def ci_cluster(rows: list[dict], field: str, draws: int = 2000) -> list[float] | None:
    if not rows:
        return None
    clusters = defaultdict(list)
    for row in rows:
        clusters[(row['task'], row['source_id'])].append(row[field])
    groups = defaultdict(list)
    for (task, _), values in clusters.items():
        groups[task].append(values)
    rng = random.Random(47)
    estimates = []
    for _ in range(draws):
        sample = []
        for block in groups.values():
            for _ in block:
                sample.extend(block[rng.randrange(len(block))])
        estimates.append(sum(sample) / len(sample))
    estimates.sort()
    return [estimates[int(.025 * draws)], estimates[int(.975 * draws)]]


def provenance(out: Path, replay_manifest: dict) -> dict:
    path = out / 'runtime.jsonl'
    if not path.exists():
        return {'neutral_runtime_recorded': False, 'same_runtime': None,
                'same_recorded_session': None,
                'note': 'Archived neutral generation has no runtime record.'}
    records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    generated = [r for r in records if r.get('command') == 'generate']
    hashes = {fingerprint_sha({'versions': r['versions'], 'device': r['device'],
                              **({'session_id': r['session_id']} if r.get('session_id') else {})})
              for r in generated}
    session_ids = sorted({r['session_id'] for r in generated if r.get('session_id')})
    return {'neutral_runtime_recorded': bool(generated),
            'neutral_generation_fingerprints': sorted(hashes),
            'neutral_session_ids': session_ids,
            'same_recorded_session': (len(session_ids) == 1 and
                                      replay_manifest['runtime'].get('session_id') == session_ids[0])
            if generated else None,
            'same_runtime': (len(hashes) == 1 and
                             replay_manifest['runtime_sha256'] in hashes)
            if hashes else None}


def load_cell(run: Path, replay_name: str, allow_partial: bool = False,
              sidecar_name: str = 'neutral_insertion') -> tuple[dict, list[dict]]:
    design, jobs = load_source(run)
    out = run / sidecar_name
    neutral_manifest = json.loads((out / 'manifest.json').read_text())
    changed = config_changes(neutral_manifest, config_for(run, design),
                             allow_relocated_run=True)
    if changed:
        raise ValueError(f'{run.name}: neutral manifest input drift: {changed}')
    neutral = load_progress(out / 'progress.jsonl', jobs)
    replay_dir = out / replay_name
    manifest = json.loads((replay_dir / 'replay_manifest.json').read_text())
    if manifest['design_id'] != design['design_id']:
        raise ValueError(f'{run.name}: replay design differs')
    if (manifest['design_sha256'] != neutral_manifest['design_sha256'] or
            manifest['traces_sha256'] != neutral_manifest['traces_sha256']):
        raise ValueError(f'{run.name}: replay and neutral use different frozen inputs')
    uncued = {job['uncued']['id']: job['uncued'] for job in jobs}
    bank = {**uncued, **({job['parent']['id']: job['parent'] for job in jobs}
                         if manifest['include_cued'] else {})}
    sample = [bank[rid] for rid, digest in manifest['sample']
              if rid in bank and bank[rid]['content_sha256'] == digest]
    if len(sample) != len(manifest['sample']):
        raise ValueError(f'{run.name}: replay sample includes unknown or changed rows')
    if not allow_partial and not set(uncued).issubset({r['id'] for r in sample}):
        raise ValueError(f'{run.name}: replay sample must cover every eligible uncued row')
    replay = load_replay(replay_dir / 'replay.jsonl', sample,
                         manifest['runtime_sha256'], manifest['code_bundle_sha256'])
    replay_uncued = {rid: rec for rid, rec in replay.items() if rid in uncued}
    if not allow_partial and (len(neutral) != len(jobs) or len(replay_uncued) != len(uncued)):
        raise ValueError(f'{run.name}: incomplete neutral/replay: '
                         f'{len(neutral)}/{len(jobs)}, {len(replay_uncued)}/{len(uncued)}')
    rows = []
    for job in jobs:
        nr = neutral.get((job['index'], job['frame']))
        rr = replay_uncued.get(job['uncued']['id'])
        if nr is None or rr is None:
            continue
        frozen = frozen_episode_answer(job['uncued'])
        new = rr['replay_answer'] if not rr['replay_hit_cap'] else None
        episode = nr.get('neutral_episode')
        if episode is None:
            raise ValueError(f'{run.name}: neutral episode missing for {job["index"]}')
        neutral_answer = None if nr['neutral_hit_cap'] else neutral_answer_fn(episode)[0]
        cue_answer = None if job['parent']['hit_cap'] else answer_v2(job['parent'])
        valid = (rr['identical_prompt_ids'] and frozen in LETTERS and
                 new in LETTERS and neutral_answer in LETTERS)
        row = {'cell': run.name, 'task': design['task'],
               'source_id': job['source_id'], 'index': job['index'],
               'frame': job['frame'], 'prompt_ids_match': rr['identical_prompt_ids'],
               'frozen_answer': frozen, 'replay_answer': new,
               'neutral_answer': neutral_answer, 'cue_answer': cue_answer,
               'cue_valid': cue_answer in LETTERS,
               'replay_tokens_match': rr['identical_tokens'],
               'valid_triplet': bool(valid)}
        if valid:
            row.update(neutral_away_frozen=int(neutral_answer != frozen),
                       replay_away_frozen=int(new != frozen),
                       neutral_away_replay=int(neutral_answer != new),
                       neutral_only_change=int(neutral_answer != frozen and new == frozen),
                       replay_only_change=int(new != frozen and neutral_answer == frozen),
                       shared_change=int(new == neutral_answer and new != frozen),
                       different_changes=int(new != frozen and neutral_answer != frozen
                                             and new != neutral_answer),
                       away_difference=int(neutral_answer != frozen) - int(new != frozen))
        rows.append(row)
    metadata = {'schema': SCHEMA, 'cell': run.name, 'task': design['task'],
                'sidecar_name': sidecar_name, 'replay_name': replay_name,
                'planned_neutral': len(jobs), 'neutral_completed': len(neutral),
                'planned_uncued': len(uncued), 'replay_completed': len(replay_uncued),
                'prompt_id_mismatches': sum(not r['identical_prompt_ids'] for r in replay_uncued.values()),
                'uncued_token_matches': sum(r['identical_tokens'] for r in replay_uncued.values()),
                'provenance': provenance(out, manifest)}
    common_code = set(neutral_manifest['code_sha256']) & set(manifest['code_sha256'])
    metadata['code_hash_matches'] = {
        name: neutral_manifest['code_sha256'][name] == manifest['code_sha256'][name]
        for name in sorted(common_code)}
    metadata['same_recorded_generation_code'] = all(metadata['code_hash_matches'].values())
    return metadata, rows


def summarize(rows: list[dict], *, include_cue: bool = False) -> dict:
    valid = [r for r in rows if r['valid_triplet']]
    result = {'neutral_replay_pairs': len(rows), 'valid_triplets': len(valid),
              'invalid_triplets': len(rows) - len(valid)}
    if not valid:
        return result
    for key in ('neutral_away_frozen', 'replay_away_frozen', 'neutral_away_replay',
                'neutral_only_change', 'replay_only_change', 'shared_change',
                'different_changes'):
        count = sum(r[key] for r in valid)
        result[key] = {'n': count, 'rate': count / len(valid),
                       'ci95': ci_cluster(valid, key)}
    result['away_difference'] = {
        'mean': sum(r['away_difference'] for r in valid) / len(valid),
        'ci95': ci_cluster(valid, 'away_difference')}
    if include_cue:
        result['cue_matched_subset'] = summarize(
            [r for r in valid if r.get('cue_valid')])
    return result


def write_rows(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(k for row in rows for k in row))
    with path.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--run', type=Path)
    group.add_argument('--runs-root', type=Path)
    parser.add_argument('--replay-name', default='full_uncued')
    parser.add_argument('--sidecar-name', default='neutral_insertion',
                        help='neutral sidecar directory within each run')
    parser.add_argument('--sidecar-map', type=Path,
                        help='optional JSON mapping cell names to replacement sidecar names')
    parser.add_argument('--output', type=Path,
                        help='aggregate JSON path; defaults to reports/e47_uncued_replay_audit.json')
    parser.add_argument('--allow-partial', action='store_true',
                        help='pilot only; never use partial results for the paper')
    args = parser.parse_args(argv)
    if args.runs_root:
        root = args.runs_root.resolve()
        runs = [root / f'{m}_{t}_thinking_v10' for m in PAPER_MODELS for t in PAPER_TASKS]
    else:
        runs = [args.run.resolve()]
    sidecar_map = json.loads(args.sidecar_map.read_text()) if args.sidecar_map else {}
    if not isinstance(sidecar_map, dict) or any(not isinstance(v, str) for v in sidecar_map.values()):
        raise ValueError('--sidecar-map must be a JSON object of cell names to directory names')
    unknown = set(sidecar_map) - {run.name for run in runs}
    if unknown:
        raise ValueError(f'--sidecar-map has unknown cells: {sorted(unknown)}')
    cells, all_rows = [], []
    for run in runs:
        meta, rows = load_cell(run, args.replay_name, args.allow_partial,
                               sidecar_map.get(run.name, args.sidecar_name))
        meta['summary'] = summarize(rows, include_cue=True)
        cells.append(meta)
        all_rows.extend(rows)
        print(f"{run.name}: replay tokens {meta['uncued_token_matches']}/{meta['replay_completed']}; "
              f"valid triplets {meta['summary']['valid_triplets']}; "
              f"neutral runtime match {meta['provenance']['same_runtime']}")
    if args.runs_root:
        output = (args.output or Path('reports/e47_uncued_replay_audit.json')).resolve()
        body = {'schema': SCHEMA, 'n_cells': len(cells), 'cells': cells,
                'all': summarize(all_rows, include_cue=True),
                'by_task': {task: summarize([r for r in all_rows if r['task'] == task],
                                           include_cue=True)
                            for task in sorted({r['task'] for r in all_rows})}}
    else:
        output = (args.output or runs[0] /
                  sidecar_map.get(runs[0].name, args.sidecar_name) / args.replay_name /
                  'neutral_comparison.json').resolve()
        body = {'schema': SCHEMA, **cells[0]}
    atomic(output, body)
    write_rows(output.with_suffix('.rows.csv'), all_rows)
    print(f'wrote {output} and {output.with_suffix(".rows.csv")}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

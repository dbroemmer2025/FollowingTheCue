#!/usr/bin/env python3
"""Generate compact per-cell RC-reader and residual-interchange LaTeX tables."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = ROOT / "reports" / "de_readers" / "results"
DEFAULT_E47 = ROOT / "e47"
DEFAULT_OUTPUT = ROOT / "tables"

MODELS = {
    "qwen2_5_7b": "Qwen2.5-7B",
    "qwen2_7b_it": "Qwen2.5-7B-Inst.",
    "gemma_2_9b_it": "Gemma-2-9B-IT",
    "mistral_nemo_instruct_2407": "Mistral-Nemo-Inst.",
    "olmo_2_1124_7b_instruct": "OLMo-2-7B-Inst.",
}
TASKS = {
    "movie_recommendations": "Movie",
    "temporal_sequences": "Temporal",
}
ORDER = {model: index for index, model in enumerate(MODELS)}
TASK_ORDER = {task: index for index, task in enumerate(TASKS)}
TEX_ROW_END = r" \\"


def read_json(path: Path) -> dict:
    with path.open() as handle:
        return json.load(handle)


def parse_cell(path: Path) -> tuple[str, str]:
    stem = path.name.removesuffix("__output.json")
    for task in TASKS:
        suffix = f"_{task}"
        if stem.endswith(suffix):
            return stem.removesuffix(suffix), task
    raise ValueError(f"Cannot parse model/task from {path.name}")


def ci(blob: dict, digits: int = 2) -> str:
    low, high = blob["ci95"]
    return f"{blob['mean']:.{digits}f} [{low:.{digits}f}, {high:.{digits}f}]"


def percent(numerator: int, denominator: int) -> str:
    if denominator <= 0:
        return "--"
    return f"{numerator}/{denominator} ({100 * numerator / denominator:.1f}\\%)"


def collect(results: Path, e47: Path) -> list[dict]:
    rows = []
    for path in sorted(results.glob("*__output.json")):
        model, task = parse_cell(path)
        if model not in MODELS or task not in TASKS:
            continue
        reader = read_json(path)
        target = reader.get("targets", {}).get("RC")
        if not target or not reader.get("output_access_control"):
            raise ValueError(f"{path}: missing output-aware RC target or provenance")
        stem = path.name.removesuffix("__output.json")
        run = e47 / f"{stem}_thinking_v10"
        causal_path = run / "causal_interchange.json"
        if not causal_path.exists():
            raise FileNotFoundError(f"Missing interchange artifact: {causal_path}")
        causal = read_json(causal_path)
        if causal.get("protocol") != "relation_matched_paired_cue_delta_interchange":
            raise ValueError(f"{causal_path}: unsupported interchange protocol")
        families = target["families"]
        extra = target["state_beyond_text_and_output"]
        joint_gain = float(families["joint_out"]["gain_over_baseline"])
        if joint_gain <= 0:
            raise ValueError(f"{path}: nonpositive Text+State gain")
        strength = causal["summaries"]["1.0/paired_delta_counterfactual"]
        shuffled = causal["primary_contrasts"][
            "paired_delta_counterfactual_minus_label_shuffled_paired_delta"]
        rescue = causal["argmax_effects"]["rescue_nonfollowers"]
        reverse = causal["argmax_effects"]["reverse_followers"]
        rows.append({
            "model": model,
            "task": task,
            "reader_items": int(target["n_items"]),
            "text_r2": float(families["text_out"]["r2"]),
            "state_r2": float(families["state"]["r2"]),
            "joint_r2": float(families["joint_out"]["r2"]),
            "share_percent": 100.0 * float(extra["share_of_joint_gain"]),
            "share_ci_percent": [
                100.0 * float(value) / joint_gain for value in extra["ci95"]],
            "interchange_items": int(strength["n_items"]),
            "strength": strength,
            "shuffled": shuffled,
            "rescue": rescue,
            "reverse": reverse,
        })
    if len(rows) != 10:
        raise ValueError(f"Expected 10 model--task cells; found {len(rows)}")
    return sorted(rows, key=lambda row: (TASK_ORDER[row["task"]], ORDER[row["model"]]))


def rc_table(rows: list[dict]) -> str:
    lines = [
        "% Generated by figures/make_e47_internal_tables.py; do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Luna-assisted, output-aware relocation-contrast (RC) reader fits by model--task cell. "
        "Text includes the rationale, original output summary, and Luna-derived estimates. "
        "All values are held-out $R^2$ except the final column, which is the residual "
        "increment as a percentage of the Text+State gain over the no-feature baseline, "
        "with a source-item-bootstrap 95\\% interval. $n$ is the number of source items "
        "in the grouped out-of-fold reader analysis.}",
        "\\label{tab:e47-rc-readers}",
        "\\scriptsize",
        "\\begin{tabular}{llrrrrr}",
        "\\toprule",
        "Model & Task & $n$ & Text & State & Text+State & Residual share [95\\% CI] \\\\",
        "\\midrule",
    ]
    for row in rows:
        low, high = row["share_ci_percent"]
        lines.append(
            f"{MODELS[row['model']]} & {TASKS[row['task']]} & {row['reader_items']} & "
            f"{row['text_r2']:.3f} & {row['state_r2']:.3f} & {row['joint_r2']:.3f} & "
            f"{row['share_percent']:.1f} [{low:.1f},{high:.1f}]" + TEX_ROW_END)
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def interchange_table(rows: list[dict]) -> str:
    lines = [
        "% Generated by figures/make_e47_internal_tables.py; do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Relation-matched residual interchange at full patch strength. "
        "Margin changes and the label-shuffled contrast are in logits, with source-item-bootstrap "
        "95\\% intervals. Rescue is the fraction of nonfollowers changed to the cue answer; "
        "reverse is the fraction of followers changed to their abandoned answer.}",
        "\\label{tab:e47-interchange}",
        "\\scriptsize",
        "\\begin{tabular}{llrrrrr}",
        "\\toprule",
        "Model & Task & $n$ & Patch margin [95\\% CI] & $-$ shuffled [95\\% CI] & Rescue & Reverse \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{MODELS[row['model']]} & {TASKS[row['task']]} & {row['interchange_items']} & "
            f"{ci(row['strength'])} & {ci(row['shuffled'])} & "
            f"{percent(row['rescue']['changed_to_counterfactual_argmax'], row['rescue']['n_items'])} & "
            f"{percent(row['reverse']['changed_to_counterfactual_argmax'], row['reverse']['n_items'])}" + TEX_ROW_END)
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--e47", type=Path, default=DEFAULT_E47)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    rows = collect(args.results.resolve(), args.e47.resolve())
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    rc = output / "tab_e47_rc_readers.tex"
    interchange = output / "tab_e47_interchange.tex"
    rc.write_text(rc_table(rows))
    interchange.write_text(interchange_table(rows))
    print(f"wrote {rc}")
    print(f"wrote {interchange}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
